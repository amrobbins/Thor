"""Export a trained XGBoost ranker to Thor's frozen C++ model header. Standard library only (reads the JSON model).

The C++ evaluator (Fp8GeometryRankerModel::margin) sums one leaf per tree, going left when feature < split. That is
XGBoost's numerical split rule; features are always finite (no missing values), so default_left never applies.
The base score is a constant offset and is omitted (it cannot change a ranking).
"""

import hashlib
import json
import struct

LEAF = 65535


def _f32(x):
    return struct.unpack("f", struct.pack("f", float(x)))[0]


def _hex(x):
    return f"{_f32(x).hex()}f"


def parse_trees(model_json):
    """[(left, right, feature, split_or_leaf)] per tree, from xgboost.Booster.save_model JSON."""
    trees = model_json["learner"]["gradient_booster"]["model"]["trees"]
    parsed = []
    for tree in trees:
        left, right = tree["left_children"], tree["right_children"]
        split_index, condition = tree["split_indices"], tree["split_conditions"]
        if any(t != 0 for t in tree.get("split_type", [])):
            raise ValueError("categorical splits are not supported by the C++ evaluator")
        nodes = []
        for i in range(len(left)):
            if left[i] == -1:
                nodes.append((LEAF, LEAF, 255, _f32(condition[i])))  # leaf value is stored as the condition
            else:
                if max(left[i], right[i]) >= LEAF or split_index[i] > 254:
                    raise ValueError("tree too large for the uint16/uint8 node encoding")
                nodes.append((left[i], right[i], split_index[i], _f32(condition[i])))
        parsed.append(nodes)
    return parsed


def margin(trees, features):
    """The C++ evaluation, in float32 order of summation."""
    total = 0.0
    for nodes in trees:
        i = 0
        while True:
            left, right, feature, value = nodes[i]
            if left == LEAF:
                total = _f32(total + value)
                break
            i = left if _f32(features[feature]) < value else right
    return total


RK_MODEL_NAMESPACE = "ThorImplementation::CubReductionInternal::Fp8RK::Fp8GeometryRankerModel"
RK_PARITY_NAMESPACE = "ThorImplementation::CubReductionInternal::Fp8RK::Fp8GeometryRankerParity"


def write_header(path, trees, feature_count, model_bytes, provenance, namespace=RK_MODEL_NAMESPACE,
                 generator="benchmarks/fp8_ranker/train.py", trained_flag=False):
    """1158: namespace / generator / trained_flag let the KR ranker (benchmarks/fp8_kr_ranker) share this exporter;
    the defaults write the RK header exactly as before."""
    sha = hashlib.sha256(model_bytes).hexdigest()
    offsets, flat = [], []
    for nodes in trees:
        offsets.append(len(flat))
        flat.extend(nodes)
    offsets.append(len(flat))
    lines = ["#pragma once",
             f"// Generated by {generator} ({provenance}); do not edit by hand.",
             f"// SHA256 of the XGBoost JSON model: {sha}",
             "// Scores are uncalibrated ranking margins (base score omitted), not predicted execution times.",
             "#include <array>", "#include <cstddef>", "#include <cstdint>", "",
             f"namespace {namespace} {{"] + (["inline constexpr bool TRAINED = true;"] if trained_flag else []) + [
             f"inline constexpr size_t FEATURE_COUNT = {feature_count};",
             "struct Node {", "    float split_or_leaf;", "    uint16_t left;", "    uint16_t right;",
             "    uint8_t feature;", "};",
             f"inline constexpr std::array<uint32_t, {len(offsets)}> tree_offsets = {{",
             "    " + ", ".join(str(o) for o in offsets), "};",
             f"inline constexpr std::array<Node, {len(flat)}> nodes = {{{{"]
    lines.append(",\n".join(f"    {{{_hex(v)}, {l}, {r}, {f}}}" for l, r, f, v in flat))
    lines += ["}};", "",
              "inline float margin(const std::array<float, FEATURE_COUNT>& features) noexcept {",
              "    float sum = 0.0f;",
              "    for (size_t tree = 0; tree + 1 < tree_offsets.size(); ++tree) {",
              "        const uint32_t offset = tree_offsets[tree];",
              "        uint16_t index = 0;",
              "        while (true) {",
              "            const auto& node = nodes[offset + index];",
              "            if (node.left == 65535) {",
              "                sum += node.split_or_leaf;",
              "                break;",
              "            }",
              "            // Numerical XGBoost splits; features are finite, so default directions never apply.",
              "            index = features[node.feature] < node.split_or_leaf ? node.left : node.right;",
              "        }",
              "    }",
              "    return sum;",
              "}",
              f"}} // namespace {namespace}", ""]
    with open(path, "w") as handle:
        handle.write("\n".join(lines))
    return sha


def write_parity_fixtures(path, trees, rows, feature_count, sha, namespace=RK_PARITY_NAMESPACE,
                          generator="benchmarks/fp8_ranker/train.py"):
    """C++ fixture header: feature vectors drawn from the dataset with the margin the exported model must produce."""
    lines = ["#pragma once",
             f"// Generated by {generator} with the model of SHA256 {sha}; do not edit by hand.",
             "#include <array>", "#include <cstddef>", "",
             f"namespace {namespace} {{",
             "struct Fixture {", f"    std::array<float, {feature_count}> features;", "    float margin;", "};",
             f"inline constexpr std::array<Fixture, {len(rows)}> fixtures = {{{{"]
    entries = []
    for features in rows:
        entries.append("    {{" + ", ".join(_hex(x) for x in features) + "}, " + _hex(margin(trees, features)) + "}")
    lines.append(",\n".join(entries))
    lines += ["}};", f"}} // namespace {namespace}", ""]
    with open(path, "w") as handle:
        handle.write("\n".join(lines))


def load_model_json(path):
    with open(path, "rb") as handle:
        data = handle.read()
    return json.loads(data), data
